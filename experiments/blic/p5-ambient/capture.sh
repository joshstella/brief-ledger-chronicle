#!/usr/bin/env bash
# capture.sh — regenerate captures/. Everything in that directory is this script's output
# against the real record, so a reader can re-run it rather than trust a pasted screenshot.
#
# The prompt capture is a real interactive bash under `script`, not a reproduction: the point
# of the surface is what PS1 renders, and a hand-built imitation of a prompt would be the one
# thing in this report nobody could check.
set -uo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO="$(git -C "$HERE" rev-parse --show-toplevel)"
OUT="$HERE/captures"
mkdir -p "$OUT"
export BLIC_CACHE_DIR="${TMPDIR:-/tmp}/blic-capture-$$"
rm -rf "$BLIC_CACHE_DIR"

banner() { printf '%s\n%s\n\n' "$1" "$(printf '%.0s=' $(seq ${#1}))"; }

# Capture 3 fires blic-warm.sh, which spawns a detached refresh by design. Without a wait,
# capture 4 reads the cache while that refresh is still rewriting it and reports whatever
# half it caught. The surfaces are fine with this — each file lands atomically — but a
# capture taken mid-refresh is a capture of a race, so the harness waits where a person
# would not have to.
wait_quiet() {
  local i
  # Sleep before the first poll. A detached refresh takes a moment to take the lock, and
  # polling immediately finds no lock, returns, and lets the capture race the very refresh it
  # was waiting for.
  sleep 0.5
  for ((i=0;i<150;i++)); do
    [ -d "$BLIC_CACHE_DIR"/*/lock ] 2>/dev/null || return 0
    sleep 0.1
  done
}

# ── 1. the shell prompt segment ──────────────────────────────────────────────
{
  banner "capture 1 — the shell prompt segment"
  echo "Generated by capture.sh against $REPO at $(date -u +%Y-%m-%dT%H:%M:%SZ)."
  echo "PS1='\\[\\e[33m\\]\$(blic_prompt)\\[\\e[0m\\] \\W \$ '"
  echo "Peer mode is ON for the second half, so the ↑ counter has something to count."
  echo "Every ↑ here is synthetic and the ~ says so."
  echo
} > "$OUT/prompt-segment.txt"

"$HERE/blic-refresh.sh" --full >/dev/null 2>&1

rc="$BLIC_CACHE_DIR/rc"
cat >"$rc" <<RC
BLIC_P5_DIR="$HERE"
. "$HERE/blic-prompt.bash"
PS1='\[\e[33m\]\$(blic_prompt)\[\e[0m\] \W \$ '
RC

# PS1 is only evaluated by an interactive shell on a terminal, so the capture needs a pty.
# Where one cannot be had — a sandbox with no /dev/ptmx, CI — fall back to expanding the same
# PS1 by hand and say so in the capture, because a reproduction presented as a transcript is
# the kind of thing this whole brief is about.
session() {
  if [ "$PTY" = 1 ]; then
    python3 "$HERE/lib/pty-session.py" "$rc" "$REPO" \
      'git rev-parse --abbrev-ref HEAD' 'ls docs/blc/briefs | wc -l' 2>/dev/null
  else
    bash --norc -c '
      BLIC_P5_DIR="$1"; BLIC_CACHE_DIR="$2"; export BLIC_CACHE_DIR
      . "$BLIC_P5_DIR/blic-prompt.bash"
      cd "$3" || exit 1
      for cmd in "git rev-parse --abbrev-ref HEAD" "ls docs/blc/briefs | wc -l"; do
        printf "%s %s $ %s\n" "$(blic_prompt)" "${PWD##*/}" "$cmd"
        eval "$cmd"
      done
      printf "%s %s $ exit\n" "$(blic_prompt)" "${PWD##*/}"
    ' _ "$HERE" "$BLIC_CACHE_DIR" "$REPO"
  fi
}

# Probe once rather than per capture.
PTY=0
if python3 -c 'import pty,os; m,s=pty.openpty(); os.close(m); os.close(s)' 2>/dev/null; then
  PTY=1
fi
if [ "$PTY" = 1 ]; then
  echo "Captured from a real interactive bash on a pty." >> "$OUT/prompt-segment.txt"
else
  echo "NO PTY AVAILABLE HERE. The transcript below is the same PS1 expanded by hand," >> "$OUT/prompt-segment.txt"
  echo "with real blic_prompt output and real command output. It is a reproduction of a" >> "$OUT/prompt-segment.txt"
  echo "prompt, not a terminal recording, and it is labelled so rather than passed off." >> "$OUT/prompt-segment.txt"
fi
echo >> "$OUT/prompt-segment.txt"

{
  echo "--- peer mode off: the real record, one author, nothing new ---"
  session
  echo
} >> "$OUT/prompt-segment.txt"

BLIC_PEER=1 "$HERE/blic-refresh.sh" --events >/dev/null 2>&1
{
  echo "--- peer mode on: five synthetic events have landed ---"
  session
  echo
  echo "The line, isolated, and its width:"
  read -r _gen line < "$BLIC_CACHE_DIR"/*/line
  printf '  %s\n  (%s characters, budget 80)\n' "$line" "${#line}"
} >> "$OUT/prompt-segment.txt"

# ── 2. the Cursor CLI status line ────────────────────────────────────────────
payload="{\"session_id\":\"capture\",\"cwd\":\"$REPO\",\"render_width_chars\":100,\"model\":{\"display_name\":\"Claude 4 Opus\",\"param_summary\":\"(Thinking)\"},\"context_window\":{\"used_percentage\":34.5},\"version\":\"1.2.3\"}"
{
  banner "capture 2 — the Cursor CLI status line"
  echo "Not installed. This is blic-statusline.sh fed the payload the skill documents."
  echo
  echo "--- stdout, rendered (what the CLI shows above the prompt) ---"
  printf '%s' "$payload" | "$HERE/blic-statusline.sh"
  echo
  echo "--- stdout, escapes visible ---"
  printf '%s' "$payload" | "$HERE/blic-statusline.sh" | cat -v
  echo
  echo "--- narrow terminal: render_width_chars 24, truncation by the payload's own width ---"
  printf '%s' "${payload/\"render_width_chars\":100/\"render_width_chars\":24}" | "$HERE/blic-statusline.sh"
  echo
  echo "--- outside a BLC repo: the record row disappears, the session row stays ---"
  printf '{"cwd":"/tmp","model":{"display_name":"Claude 4 Opus"},"context_window":{"used_percentage":2}}' \
    | "$HERE/blic-statusline.sh"
} > "$OUT/cursor-statusline.txt"

# ── 3. the hooks ─────────────────────────────────────────────────────────────
{
  banner "capture 3 — the notification hooks"
  echo "Not installed. These are the scripts fed the stdin a hook event carries."
  echo
  echo "--- beforeShellExecution, record moved (peer mode on) ---"
  printf '{"cwd":"%s","command":"git push origin HEAD"}' "$REPO" | "$HERE/hooks/blic-notify.sh"
  echo
  echo "--- beforeShellExecution, nothing new: allow, no message, no interruption ---"
  "$HERE/blic-refresh.sh" --baseline >/dev/null 2>&1
  printf '{"cwd":"%s","command":"git push origin HEAD"}' "$REPO" | "$HERE/hooks/blic-notify.sh"
  echo
  echo "--- beforeShellExecution, outside a BLC repo: allow, silent ---"
  printf '{"cwd":"/tmp","command":"git push"}' | "$HERE/hooks/blic-notify.sh"
  echo
  echo "--- sessionStart / stop: blic-warm.sh returns nothing and refreshes detached ---"
  printf '{"cwd":"%s"}' "$REPO" | "$HERE/hooks/blic-warm.sh"; echo "(exit $?; no stdout by design)"
} > "$OUT/hooks.txt"

# ── 4. the out-of-band detail ────────────────────────────────────────────────
# Capture 3 acknowledged everything, so re-take the baseline against the real record only and
# then let the peer events land on top of it. That is the sequence a second contributor
# produces, and it is the only way this fixture can produce it at all.
wait_quiet
rm -f "$BLIC_CACHE_DIR"/*/seen
"$HERE/blic-refresh.sh" --events >/dev/null 2>&1
BLIC_PEER=1 "$HERE/blic-refresh.sh" --events >/dev/null 2>&1
{
  banner "capture 4 — blic why and blic doctor"
  echo "--- blic why: the lines behind the one line ---"
  BLIC_PEER=1 "$HERE/bin/blic" why
  echo
  echo "--- blic doctor ---"
  "$HERE/bin/blic" doctor
} > "$OUT/blic-why.txt"

rm -rf "$BLIC_CACHE_DIR"
echo "wrote $OUT/{prompt-segment,cursor-statusline,hooks,blic-why}.txt"
